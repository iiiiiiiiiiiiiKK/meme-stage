import { chromium } from "@playwright/test";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 860 } });
page.on("console", (m) => console.log("console", m.type(), m.text().slice(0, 300)));
page.on("pageerror", (e) => console.log("pageerror", e.message, e.stack?.split("\n").slice(0, 4).join("\n")));
page.on("requestfailed", (r) => console.log("failed", r.url(), r.failure()?.errorText));
await page.goto("https://meme-stage.pages.dev/editor", { waitUntil: "domcontentloaded" });
await page.waitForTimeout(4000);
console.log("body", (await page.locator("body").innerText()).slice(0, 300));
await browser.close();
