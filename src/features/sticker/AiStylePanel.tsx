/**
 * AI style panel (bring-your-own-key).
 *
 * Gated on the user's own key, states that the sticker is sent to a third party, and
 * reports the real usage numbers. A failure never becomes a fake result: the original
 * sticker is only ever read, and the restyle is saved as a new version.
 */
import { useCallback, useEffect, useState } from "react";
import { Button, Field, Select, Spinner, TextArea, toast } from "../../components/ui";
import { Icon } from "../../components/Icon";
import { AiKeyPanel } from "./AiKeyPanel";
import { aiReady, useAiKey, useAiKeyStore } from "./useAiKey";
import { downloadGenerated, restyleImage, usageSummary } from "./byok";

const STYLE_PRESETS: { id: string; label: string; prompt: string }[] = [
  {
    id: "comic",
    label: "美式漫画",
    prompt:
      "restyle into a bold American comic sticker: flat cel shading, thick black ink outline, keep the exact same person, face, pose and clothing, no text, no extra objects",
  },
  {
    id: "retro",
    label: "复古印刷",
    prompt:
      "restyle into a retro screen-print sticker: limited palette, halftone texture, keep the exact same face, pose and clothing, no text",
  },
  {
    id: "pixel",
    label: "像素艺术",
    prompt:
      "restyle into clean pixel art sticker: crisp square pixels, limited palette, keep the same character and pose, no text",
  },
  {
    id: "mono",
    label: "黑白颗粒",
    prompt:
      "restyle into high-contrast black and white film sticker: grainy texture, keep the exact same person and pose, no text",
  },
  {
    id: "duotone",
    label: "双色调",
    prompt:
      "restyle into a two-tone sticker with a bold duotone palette, keep the same person and pose, no text",
  },
];

export function AiStylePanel({
  variantName,
  sourceBlob,
  onResult,
}: {
  variantName: string;
  /** the sticker bytes to restyle; the original is never modified */
  sourceBlob: Blob | null;
  /** receives the generated bytes; the caller decides how to store them */
  onResult: (blob: Blob, name: string) => void;
}) {
  const ai = useAiKey();
  const hydrate = useAiKeyStore((s) => s.hydrate);
  useEffect(() => {
    hydrate();
  }, [hydrate]);
  const [open, setOpen] = useState(false);
  const [preset, setPreset] = useState(STYLE_PRESETS[0].id);
  const [custom, setCustom] = useState("");
  const [busy, setBusy] = useState(false);
  const [step, setStep] = useState<string | null>(null);
  const [lastUsage, setLastUsage] = useState<string | null>(null);
  const [confirmed, setConfirmed] = useState(false);
  const [transparent, setTransparent] = useState(false);

  // A restyle consumes the confirmation, so a second run cannot piggyback on it.
  useEffect(() => {
    if (ai.error) setConfirmed(false);
  }, [ai.error]);

  const run = useCallback(async () => {
    if (!sourceBlob) {
      toast("这张贴纸的本机文件已不在，无法转换", "error");
      return;
    }
    if (!ai.key) {
      toast("先设置你自己的 AI 密钥", "info");
      return;
    }
    if (!confirmed) {
      toast("请先勾选确认，图像会发送给外部模型服务", "info");
      return;
    }
    const active = STYLE_PRESETS.find((item) => item.id === preset);
    const prompt = custom.trim() || active?.prompt || "";
    setBusy(true);
    setLastUsage(null);
    try {
      const result = await restyleImage({
        key: ai.key,
        file: sourceBlob,
        prompt,
        model: ai.model || undefined,
        size: "1024x1024",
        // Transparency is the slow path on this gateway, so it stays opt-in even
        // though it is usually what you want for a sticker.
        background: transparent ? "transparent" : undefined,
        onProgress: setStep,
      });
      setStep("正在下载结果…");
      const blob = await downloadGenerated(result.sourceUrl);
      setLastUsage(usageSummary(result.usage));
      toast("风格版已生成", "success");
      onResult(blob, `${variantName.slice(0, 24)} · AI`);
    } catch (error) {
      toast(error instanceof Error ? error.message : "生成失败", "error");
    } finally {
      setBusy(false);
      setStep(null);
    }
  }, [ai.key, ai.model, confirmed, custom, onResult, preset, sourceBlob, transparent, variantName]);

  return (
    <div className="space-y-1.5">
      <AiKeyPanel compact />

      <div className="rounded border border-line/70 bg-ink px-2 py-1.5">
        <button
          type="button"
          onClick={() => setOpen((value) => !value)}
          className="flex w-full items-center gap-1 text-[10px] font-semibold text-paper"
        >
          <Icon name="sparkles" size={10} /> AI 风格版
          <span className="ml-auto text-[9px] font-normal text-mute">{open ? "收起" : "展开"}</span>
        </button>

        {open ? (
          <div className="mt-1.5 space-y-1.5">
            {!sourceBlob ? (
              <p className="text-[9px] leading-relaxed text-amber-300">
                这张贴纸的本机文件已不在（可能清理过浏览器数据），请重新保存一张再做风格化。
              </p>
            ) : null}
            {!aiReady(ai) ? (
              <p className="text-[9px] leading-relaxed text-amber-300">
                需要先在上面填入你自己的密钥才能生成。
              </p>
            ) : null}

            <Field label="风格">
              <Select
                value={preset}
                aria-label="AI 风格"
                className="h-7 text-[11px]"
                onChange={(e) => setPreset(e.target.value)}
              >
                {STYLE_PRESETS.map((item) => (
                  <option key={item.id} value={item.id}>
                    {item.label}
                  </option>
                ))}
              </Select>
            </Field>

            <Field label="模型">
              <Select
                value={ai.model}
                aria-label="AI 模型"
                className="h-7 text-[11px]"
                onChange={(e) => ai.setModel(e.target.value)}
              >
                {(ai.models.length > 0 ? ai.models : ["gpt-image-2.5"]).map((id) => (
                  <option key={id} value={id}>
                    {id}
                  </option>
                ))}
              </Select>
            </Field>

            <Field label="自定义提示词（可选）">
              <TextArea
                value={custom}
                onChange={(e) => setCustom(e.target.value)}
                placeholder="留空使用上面的风格预设"
                rows={2}
                className="text-[10.5px]"
              />
            </Field>

            <label className="flex items-start gap-1.5 text-[9px] leading-relaxed text-mute">
              <input
                type="checkbox"
                checked={transparent}
                onChange={(e) => setTransparent(e.target.checked)}
                className="mt-0.5 h-3 w-3 accent-[#b6ff3c]"
              />
              <span>要求透明背景（较慢，容易超时；不需要时留空，生成后本机抠图更稳）</span>
            </label>

            <label className="flex items-start gap-1.5 text-[9px] leading-relaxed text-mute">
              <input
                type="checkbox"
                checked={confirmed}
                onChange={(e) => setConfirmed(e.target.checked)}
                className="mt-0.5 h-3 w-3 accent-[#b6ff3c]"
              />
              <span>
                我确认：当前贴纸会直接从我的浏览器发送到外部模型服务（费用计入我的账号）；生成结果另存为新版本，原图和本地抠图不会被覆盖。
              </span>
            </label>

            <Button
              size="sm"
              variant="secondary"
              icon="sparkles"
              className="w-full"
              disabled={busy || !confirmed || !sourceBlob || !aiReady(ai)}
              onClick={() => void run()}
            >
              {busy ? <Spinner size={11} /> : null}
              {busy ? "生成中…" : "生成风格版"}
            </Button>

            {step ? <div className="text-[9px] text-mute">{step}</div> : null}
            {lastUsage ? <div className="text-[9px] text-mute">用量：{lastUsage}</div> : null}
            {busy ? (
              <div className="text-[9px] leading-relaxed text-mute">
                典型耗时 20–40 秒，期间请不要关闭页面。
              </div>
            ) : null}
          </div>
        ) : null}
      </div>
    </div>
  );
}
